"""Local Ollama adapter. Uses the loopback service and the existing reply validator."""

from __future__ import annotations

import json
from urllib.error import HTTPError, URLError
from urllib.request import ProxyHandler, Request, build_opener

from .adapter import AdapterError, ModelInput
from .live import REPLY_SCHEMA, SYSTEM_PROMPT

DEFAULT_MODEL = "qwen3:4b"
ENDPOINT = "http://127.0.0.1:11434/api/chat"
MAX_RESPONSE_BYTES = 256 * 1024
LOCAL_RULES = """
Before writing SQL, check whether the question specifies its measure and scope.
For any ranking request, both the ranking measure and number of results must be supplied.
If both are missing, ask: Should I rank by paid revenue or units sold, and how many results should I show?
If one is missing, ask for that missing information. Never invent a ranking measure or a top-ten limit.
For an unsupported request, ask one direct question about an allowed analytics task.
Give each computed result a meaningful alias. Every money alias must end in _cents.
Use an explicit ORDER BY when returning multiple rows.
"""


class OllamaAdapter:
    """Generate SQL locally without credentials or an external model service."""

    def __init__(self, model: str = DEFAULT_MODEL, *, timeout: float = 90.0) -> None:
        self.model = model
        self.timeout = timeout
        self.label = f"LOCAL MODEL {model} - generated by Ollama on this computer."

    def propose(self, model_input: ModelInput) -> object:
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT + LOCAL_RULES},
                {"role": "user", "content": model_input.render()},
            ],
            "stream": False,
            "think": True,
            "format": REPLY_SCHEMA,
            "options": {
                "temperature": 0,
                "seed": 42,
                "num_ctx": 4096,
                "num_predict": 2048,
            },
        }
        request = Request(
            ENDPOINT,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        # Ignore configured proxies. Model requests go directly to the loopback service.
        opener = build_opener(ProxyHandler({}))
        try:
            with opener.open(request, timeout=self.timeout) as response:
                raw = response.read(MAX_RESPONSE_BYTES + 1)
        except HTTPError as exc:
            if exc.code == 404:
                raise AdapterError(
                    f"Ollama could not find {self.model!r}; install that model in Ollama"
                ) from None
            raise AdapterError(f"local model request failed (HTTP {exc.code})") from None
        except (URLError, OSError) as exc:
            raise AdapterError(
                f"could not reach the local model ({type(exc).__name__}); check that Ollama is running"
            ) from None

        if len(raw) > MAX_RESPONSE_BYTES:
            raise AdapterError("local model response is too large")
        try:
            body = json.loads(raw)
        except (ValueError, UnicodeError, RecursionError):
            raise AdapterError("local model returned an unusable JSON response") from None
        if not isinstance(body, dict):
            raise AdapterError("local model response must be an object")
        if body.get("done") is not True or body.get("done_reason") != "stop":
            raise AdapterError("local model did not finish its reply; nothing was executed")
        message = body.get("message")
        if not isinstance(message, dict) or message.get("role") != "assistant":
            raise AdapterError("local model returned an unexpected message")
        if message.get("tool_calls") or not isinstance(message.get("content"), str):
            raise AdapterError("local model must return a text reply")
        # The CLI applies parse_response before it can call the restricted executor.
        return message["content"]

    def answer_context(self, question: str) -> str:
        return ""
